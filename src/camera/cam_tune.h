/* Настройки изображения. Применяются один раз при запуске камеры, из портала и HA не меняются.
   Сенсор определяется на лету по PID, поэтому значения разделены по сенсорам (OV3660 / OV5640),
   а не по плате: любая из двух плат может нести любой из двух сенсоров.
   Ниже: [диапазон], предпочтительное значение, и что делает параметр.
   Для начала взяты значения против "тумана"; подбирайте по картинке. */

/* ------------------------------------------------------------------ OV3660 */
#define CAM_OV3660_BRIGHTNESS   0   /* [-3..3]  0: яркость. Больше - светлее. Лучше менять экспозицией, не этим */
#define CAM_OV3660_CONTRAST     3   /* [-3..3]  +1: контраст. Главный параметр против "тумана" */
#define CAM_OV3660_SATURATION   1   /* [-4..4]  +1: насыщенность цвета */
#define CAM_OV3660_SHARPNESS    2   /* [-3..3]  +2: резкость (программное усиление краёв) */
#define CAM_OV3660_DENOISE      0   /* [0..8]   2: шумоподавление, 0 = выкл. Больше - чище, но мягче картинка */
#define CAM_OV3660_LENC         0   /* 0/1      1: коррекция виньетирования (затемнения по краям) */
#define CAM_OV3660_WARMUP_PHOTO 10  /* [0..30]  8: сколько кадров выбросить после старта перед фото */
#define CAM_OV3660_WARMUP_STREAM 3  /* [0..30]  3: то же перед стримом */

/* ------------------------------------------------------------------ OV5640 */
#define CAM_OV5640_BRIGHTNESS   0   /* [-3..3]  0 */
#define CAM_OV5640_CONTRAST     3   /* [-3..3]  +1 */
#define CAM_OV5640_SATURATION   1   /* [-4..4]  +1 */
#define CAM_OV5640_SHARPNESS    2   /* [-3..3]  +2 */
#define CAM_OV5640_DENOISE      0   /* [0..8]   2 */
#define CAM_OV5640_LENC         1   /* 0/1      1 */
#define CAM_OV5640_WARMUP_PHOTO 5   /* [0..30]  10: у OV5640 автоэкспозиция сходится дольше */
#define CAM_OV5640_WARMUP_STREAM 3  /* [0..30]  3 */

/* Автофокус OV5640 (только модули с AF-объективом; подробности в README esp32-camera).
   Нужно включить в menuconfig: Component config -> Camera configuration -> Enable autofocus (OV5640).
   Без этого, на сенсоре без AF и на OV3660 код автофокуса просто ничего не делает. */
#define CAM_OV5640_AF_ENABLE    0     /* 0/1      1: захватить фокус после прогрева, перед первым кадром */
#define CAM_OV5640_AF_TIMEOUT_MS 3000 /* [500..8000] 3000: сколько ждать сведения фокуса */

/* Если сенсор другой (OV2640 и т.д.): настройки не применяются, прогрев 4 кадра для фото и 2 для стрима */
#define CAM_OTHER_WARMUP_PHOTO  4
#define CAM_OTHER_WARMUP_STREAM 2
